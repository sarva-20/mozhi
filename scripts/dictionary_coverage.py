"""
Full-dictionary coverage test: for every domain term, generate plausible mis-transcriptions,
run each through correct_text() inside a neutral carrier sentence, and report the catch-rate
per term, per corruption operator, and the concrete list of terms Mozhi fails to recover.

THIS IS A SYNTHETIC TEST. The corruptions are generated by rules, not recorded from speakers.
It measures robustness to the kinds of error the rules imitate; it is NOT a measurement of
real-world STT accuracy, which needs real recordings (scripts/evaluate_accuracy.py). Real
Whisper errors are dominated by substitutions with real words ("read" for "RAID"), which rules
only partly imitate. The operators are deliberately orthographic / phonetic-rule based and not
Metaphone based, because Mozhi scores with Metaphone and a Metaphone-built corruption set
would flatter it.

Variant families, per term
  canonical      the term exactly as the dictionary spells it. A CONTROL: it must come back
                 unchanged. A failure here is a pipeline defect, not a coverage gap.
  acronym_map    spoken forms already hand-enumerated in ACRONYM_PHONETIC_MAP. Exact lookups,
                 so ~100% by construction: a regression check, not a coverage measure.
  phrase_alias   entries in PHRASE_ALIASES. Same caveat.
  spelled        letter-by-letter spelling of an acronym ("ess ess dee"): the composer path.
  spelled_token  a phrase with its acronym token spelled out ("eye pea address").
  synthetic      rule-based corruptions (see OPERATORS). The informative family.

A variant is RECOVERED when the corrected sentence equals the carrier with the canonical term in
place, compared WORD BY WORD, case- and punctuation-insensitively (the same convention as
scripts/evaluate_accuracy.py). So "two factor authentication" counts as recovering "two-factor
authentication" (only the hyphen differs), while partial matches, duplicated words ("firewall
firewall") and collateral edits to the carrier still count as failures. A byte-exact column is
kept so the cosmetic gap stays visible. Outcomes: recovered | missed (Mozhi changed nothing) |
garbled (the right term is in the output but the sentence is not right: leftover, duplicated or
swallowed words) | wrong (something else came out).

Plurals are not generated: "routers" is correct English, and whether Mozhi should singularize it
is a product decision, not a phonetic mis-transcription.

Deterministic: variant choice is ordered by a CRC32 of (term, operator, text), never by an RNG.

Run:
    PYTHONPATH=. python3 scripts/dictionary_coverage.py [--workers N] [--limit N] [--terms a,b]
Writes reports/dictionary_coverage_variants.csv, _terms.csv and _summary.txt.
"""
