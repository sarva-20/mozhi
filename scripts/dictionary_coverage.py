VARIANT_FIELDS = ["term", "category", "shape", "n_words", "family", "operator", "variant", "outcome", "exact", "output", "mozhi_edits"]
TERM_FIELDS = ["term", "category", "shape", "n_words", "canonical_ok", "evaluated_n", "evaluated_caught", "evaluated_rate",
               "synthetic_n", "synthetic_caught", "synthetic_rate", "failing_operators"]


def write_csvs(results: list[Result], variants_path: Path, terms_path: Path) -> None:
    variants_path.parent.mkdir(parents=True, exist_ok=True)
    with open(variants_path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(VARIANT_FIELDS)
        for r in results:
            w.writerow([r.term, r.category, r.shape, r.n_words, r.family, r.operator, r.variant, r.outcome,
                        "yes" if r.exact else "no", r.output, r.edits])
    fmt = lambda x: "" if x is None else f"{x:.3f}"  # noqa: E731
    with open(terms_path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(TERM_FIELDS)
        for t in sorted(term_rows(results), key=lambda t: (t.synthetic_rate if t.synthetic_rate is not None else 2, t.term)):
            w.writerow([t.term, t.category, t.shape, t.n_words, "yes" if t.canonical_ok else "NO", t.evaluated_n,
                        t.evaluated_caught, fmt(t.evaluated_rate), t.synthetic_n, t.synthetic_caught,
                        fmt(t.synthetic_rate), t.failing_operators])


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--workers", type=int, default=min(8, os.cpu_count() or 1))
    p.add_argument("--limit", type=int, default=0, help="only the first N terms (quick check)")
    p.add_argument("--terms", default="", help="comma-separated terms to test")
    p.add_argument("--carrier", default=CARRIER)
    p.add_argument("--out-dir", type=Path, default=REPORTS, help="where the three report files go (default: reports/)")
    args = p.parse_args(argv)

    entries = {t["term"]: t for t in get_terms()}
    all_terms = list(entries)
    chosen = [t.strip() for t in args.terms.split(",") if t.strip()] or all_terms
    unknown = [t for t in chosen if t not in entries]
    if unknown:
        print(f"ERROR: not in the dictionary: {unknown}")
        return 1
    if args.limit:
        chosen = chosen[: args.limit]
    variants = [v for t in chosen for v in generate_variants(t, all_terms)]
    print(f"{len(chosen)} terms -> {len(variants)} variants, {args.workers} worker(s)...")
    start = time.time()
    results = evaluate(variants, entries, args.carrier, workers=args.workers)
    summary = summarize(results, len(chosen), args.carrier, time.time() - start)
    out = args.out_dir
    write_csvs(results, out / VARIANTS_CSV.name, out / TERMS_CSV.name)
    (out / SUMMARY_TXT.name).write_text(summary, encoding="utf-8")
    print(summary)
    print(f"Wrote {VARIANTS_CSV.name}, {TERMS_CSV.name}, {SUMMARY_TXT.name} in {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
